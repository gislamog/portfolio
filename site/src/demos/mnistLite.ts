export function downsample28to8(pixels: number[]): number[] {
  const out = new Array(64).fill(0);
  const counts = new Array(64).fill(0);
  for (let y = 0; y < 28; y++) {
    for (let x = 0; x < 28; x++) {
      const i = Math.floor(y / 3.5) * 8 + Math.floor(x / 3.5);
      if (i >= 0 && i < 64) {
        out[i] += pixels[y * 28 + x];
        counts[i] += 1;
      }
    }
  }
  return out.map((v, i) => (counts[i] ? v / counts[i] : 0));
}

export function classifyDigit(grid8: number[]) {
  let best = 0;
  let bestScore = -Infinity;
  const scores = DIGIT_PROTOS.map((proto, digit) => {
    let dot = 0;
    let na = 0;
    let nb = 0;
    for (let i = 0; i < 64; i++) {
      dot += grid8[i] * proto[i];
      na += grid8[i] * grid8[i];
      nb += proto[i] * proto[i];
    }
    const score = na && nb ? dot / Math.sqrt(na * nb) : 0;
    if (score > bestScore) {
      bestScore = score;
      best = digit;
    }
    return { digit, score };
  });
  return { digit: best, confidence: bestScore, scores };
}
